"""Render compiler-owned nginx/Angie directives without rewriting user snippets."""


class Snippet(str):
    """Opaque configuration or embedded code, preserved verbatim."""


def render_config(lines, description):
    description = "".join(char if char.isprintable() else " " for char in description)
    output = ["# Generated by APM. Changes are replaced on apply.", f"# {description}", ""]
    depth = 0
    for source in lines:
        if isinstance(source, Snippet):
            if source:
                output.append(str(source))
            continue
        for line in source.splitlines():
            buffer = ""
            quote = None
            escaped = False

            def flush():
                nonlocal buffer
                if buffer.strip():
                    output.append("    " * depth + buffer.strip())
                buffer = ""

            for index, char in enumerate(line):
                if escaped:
                    buffer += char
                    escaped = False
                elif char == "\\":
                    buffer += char
                    escaped = True
                elif quote:
                    buffer += char
                    if char == quote:
                        quote = None
                elif char in ("'", '"'):
                    quote = char
                    buffer += char
                elif char == "#":
                    flush()
                    output.append("    " * depth + line[index:])
                    break
                elif char == "{":
                    buffer += char
                    flush()
                    depth += 1
                elif char == "}":
                    flush()
                    depth -= 1
                    output.append("    " * depth + "}")
                elif char == ";":
                    buffer += char
                    flush()
                else:
                    buffer += char
            else:
                flush()
    return "\n".join(output) + "\n"
